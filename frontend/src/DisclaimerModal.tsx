import { useEffect, useRef } from 'react';

// Shown every time the app opens: the user has to acknowledge that this is a
// research tool and not a medical diagnosis before using it.
export default function DisclaimerModal({ onAccept }: { onAccept: () => void }) {
  const buttonRef = useRef<HTMLButtonElement>(null);

  useEffect(() => {
    buttonRef.current?.focus();
    const prev = document.body.style.overflow;
    document.body.style.overflow = 'hidden';
    return () => {
      document.body.style.overflow = prev;
    };
  }, []);

  return (
    <div className="fixed inset-0 z-[60] bg-black/60 backdrop-blur-sm flex items-center justify-center p-4">
      <div
        role="alertdialog"
        aria-modal="true"
        aria-labelledby="disclaimer-title"
        aria-describedby="disclaimer-body"
        className="w-full max-w-lg rounded-[24px] p-6 sm:p-7 bg-surface border border-line text-ink
                   shadow-[0_24px_60px_rgba(0,0,0,0.35)] font-['IBM_Plex_Sans',sans-serif]"
      >
        <div className="flex items-center gap-3">
          <span className="w-11 h-11 rounded-2xl bg-danger-bg border border-danger-line text-danger flex items-center justify-center shrink-0">
            <svg width="22" height="22" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2"
              strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
              <path d="M12 3L2 20h20L12 3zM12 10v4M12 17.5v.01" />
            </svg>
          </span>
          <h2 id="disclaimer-title" className="text-[20px] font-bold tracking-tight font-['IBM_Plex_Sans',sans-serif]">
            This is not a medical diagnosis
          </h2>
        </div>

        <div id="disclaimer-body" className="mt-4 text-[14px] leading-relaxed text-muted space-y-3">
          <p>
            ESMA Dental is a <b className="text-ink">research prototype</b> made for academic demonstration only.
          </p>
          <ul className="list-disc pl-5 space-y-1.5">
            <li>The highlighted areas are generated by a computer model and may be wrong or incomplete.</li>
            <li>The results must not be used to diagnose, treat or rule out any dental condition.</li>
            <li>Always consult a licensed dentist for an actual diagnosis or treatment.</li>
          </ul>
        </div>

        <button
          ref={buttonRef}
          onClick={onAccept}
          className="neu-btn mt-6 w-full min-h-[48px] rounded-xl bg-btn text-btn-fg text-[16px] font-semibold
                     hover:bg-[var(--btn-hover)] transition-colors"
        >
          I understand, continue
        </button>
      </div>
    </div>
  );
}
